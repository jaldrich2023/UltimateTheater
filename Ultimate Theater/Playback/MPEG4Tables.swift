/// A codeword table decoded with a single lookup: `bits` bits are peeked and the entry gives
/// the symbol and its length. Entries for bit patterns that aren't codewords are zero.
nonisolated struct MPEG4VLC: Sendable {
    let bits: Int
    /// `symbol << 8 | length`; 0 = invalid.
    let table: [Int32]

    init(codes: [String]) {
        let longest = codes.map(\.count).max() ?? 1
        var table = [Int32](repeating: 0, count: 1 << longest)
        for (symbol, code) in codes.enumerated() {
            var value = 0
            for character in code { value = value << 1 | (character == "1" ? 1 : 0) }
            let shift = longest - code.count
            let first = value << shift
            for index in first..<(first + (1 << shift)) {
                table[index] = Int32(symbol << 8 | code.count)
            }
        }
        self.bits = longest
        self.table = table
    }
}
